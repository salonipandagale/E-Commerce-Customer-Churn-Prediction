import streamlit as st
import pandas as pd
import joblib

model = joblib.load("churn_random_forest_pipeline.pkl")

st.set_page_config(
    page_title="E-Commerce Churn Predictor",
    page_icon="📊",
    layout="wide"
)

st.title("📊 E-Commerce Customer Churn Predictor")
st.write("Enter the customer's details to predict the probability of churn.")

st.header("Customer Information")

col1, col2, col3 = st.columns(3)

with col1:
    tenure = st.number_input(
        "Tenure (months)",
        min_value=0.0,
        max_value=61.0,
        value=5.0
    )

    login_device = st.selectbox(
        "Preferred Login Device",
        ["Mobile Phone", "Computer", "Phone"]
    )

    city_tier = st.selectbox(
        "City Tier",
        [1, 2, 3]
    )

    warehouse_distance = st.number_input(
        "Warehouse to Home Distance",
        min_value=5.0,
        max_value=127.0,
        value=15.0
    )

    payment_mode = st.selectbox(
        "Preferred Payment Mode",
        [
            "Debit Card",
            "Credit Card",
            "E wallet",
            "UPI",
            "Cash on Delivery"
        ]
    )

with col2:
    gender = st.selectbox(
        "Gender",
        ["Male", "Female"]
    )

    app_hours = st.number_input(
        "Hours Spent on App",
        min_value=0.0,
        max_value=5.0,
        value=3.0
    )

    devices = st.number_input(
        "Number of Devices Registered",
        min_value=1,
        max_value=6,
        value=4
    )

    order_category = st.selectbox(
        "Preferred Order Category",
        [
            "Laptop & Accessory",
            "Mobile Phone",
            "Fashion",
            "Mobile",
            "Grocery",
            "Others"
        ]
    )

    satisfaction = st.selectbox(
        "Satisfaction Score",
        [1, 2, 3, 4, 5]
    )

with col3:
    marital_status = st.selectbox(
        "Marital Status",
        ["Married", "Single", "Divorced"]
    )

    number_address = st.number_input(
        "Number of Addresses",
        min_value=1,
        max_value=22,
        value=3
    )

    complaint = st.selectbox(
        "Has Customer Complained?",
        ["No", "Yes"]
    )

    order_hike = st.number_input(
        "Order Amount Hike From Last Year (%)",
        min_value=11.0,
        max_value=26.0,
        value=15.0
    )

    coupon_used = st.number_input(
        "Coupons Used",
        min_value=0.0,
        max_value=16.0,
        value=1.0
    )

st.header("Order Activity")

col4, col5, col6 = st.columns(3)

with col4:
    order_count = st.number_input(
        "Order Count",
        min_value=1.0,
        max_value=16.0,
        value=2.0
    )

with col5:
    days_last_order = st.number_input(
        "Days Since Last Order",
        min_value=0.0,
        max_value=46.0,
        value=3.0
    )

with col6:
    cashback = st.number_input(
        "Cashback Amount",
        min_value=0.0,
        max_value=325.0,
        value=160.0
    )

st.divider()

if st.button("🔍 Predict Churn", use_container_width=True):

    complaint_value = 1 if complaint == "Yes" else 0

    input_data = pd.DataFrame({
        "Tenure": [tenure],
        "PreferredLoginDevice": [login_device],
        "CityTier": [city_tier],
        "WarehouseToHome": [warehouse_distance],
        "PreferredPaymentMode": [payment_mode],
        "Gender": [gender],
        "HourSpendOnApp": [app_hours],
        "NumberOfDeviceRegistered": [devices],
        "PreferedOrderCat": [order_category],
        "SatisfactionScore": [satisfaction],
        "MaritalStatus": [marital_status],
        "NumberOfAddress": [number_address],
        "Complain": [complaint_value],
        "OrderAmountHikeFromlastYear": [order_hike],
        "CouponUsed": [coupon_used],
        "OrderCount": [order_count],
        "DaySinceLastOrder": [days_last_order],
        "CashbackAmount": [cashback]
    })

    prediction = model.predict(input_data)[0]
    probability = model.predict_proba(input_data)[0][1]

    st.header("Prediction Result")

    if prediction == 1:
        st.error("⚠️ HIGH CHURN RISK")
        st.metric("Churn Probability", f"{probability * 100:.2f}%")
        st.warning(
            "This customer is predicted to be at high risk of churn. "
            "Consider targeted retention actions."
        )
    else:
        st.success("✅ LOW CHURN RISK")
        st.metric("Churn Probability", f"{probability * 100:.2f}%")
        st.info(
            "This customer is predicted to have a lower risk of churn."
        )

    st.write("### Churn Probability")
    st.progress(float(probability))
    st.caption("Prediction generated using the trained Random Forest model.")